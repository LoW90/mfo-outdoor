/** Writes images/README.md and docs/MEDIA_SLOTS.md from planner/media.mjs and the generator's slot list, so the
 *  slot lists cannot drift from what the theme bundles. `node planner/docs.mjs --audit <file>` also writes the slot
 *  table rows to <file> (the portfolio launch audit). */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {mediaSlots} from '../build.mjs';
import {slots} from './media.mjs';
import {loadCatalog} from './build.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const cell = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function table(c = loadCatalog()) {
  const rows = ['| Slot id | Film or photo | File name and folder | Size / format | Where it appears | Status | What it should show |', '|---|---|---|---|---|---|---|'];
  for (const s of slots(c)) rows.push(`| \`${s.id}\` | ${s.type}${s.optional ? ' (optional)' : ''} | \`${s.folder}${s.file}\` | ${cell(s.size)} | ${cell(s.where)} | ${s.status} | ${cell(s.brief)} |`);
  return rows.join('\n');
}
export function counts(c = loadCatalog()) {
  const all = slots(c), n = (type, status, opt) => all.filter(s => s.type === type && s.status === status && (opt === undefined || !!s.optional === opt)).length;
  return {filmsFilled: n('film', 'filled'), filmsMissing: n('film', 'missing', false), optionalFilmsMissing: n('film', 'missing', true), photosFilled: n('photo', 'filled'), photosMissing: n('photo', 'missing')};
}

export function mediaDoc(c = loadCatalog()) {
  const k = counts(c);
  return `# Media slots: ${c.name}

**Films need only the .mp4.** \`npm run build\` makes each film's .webp cover still from its first second when that file is missing (and \`hero.webp\` from \`hero-film.mp4\`), using ffmpeg if it is installed. A .webm copy is optional.

Generated by \`shopify/planner/docs.mjs\`. Do not edit; run \`npm test\` (or \`node planner/docs.mjs\`) in \`shopify/\`.

Drop a file named exactly as below into \`images/\` at the repo root, then run \`npm run build\` in \`shopify/\`: the build
bundles it into the theme and the page shows it with its "Original AI-generated" label. A missing file never shows an
empty box or slot text: the hero keeps its dark band, maker tiles show a monogram, product cards a toned frame, and the film bands stay hidden.
Films can also be picked in the Shopify theme editor (home page section settings).

Films: ${k.filmsFilled} filled, ${k.filmsMissing} missing (plus ${k.optionalFilmsMissing} optional maker films). Photos: ${k.photosFilled} filled, ${k.photosMissing} missing.

${table(c)}

Rules: photoreal, luxury, real-looking older affluent people where people appear; no logos, brand badges or text; label
AI-generated media (the theme does this); use a maker's own photos or films only with their written permission.
`;
}

export function imagesReadme(c = loadCatalog()) {
  return `# ${c.name}: photographs and films

**Films need only the .mp4.** \`npm run build\` makes each film's .webp cover still from its first second when that file is missing (and \`hero.webp\` from \`hero-film.mp4\`), using ffmpeg if it is installed. A .webm copy is optional.

Original photorealistic media only: never drawings or SVG stand-ins, and no films borrowed from another Many Faces store.
Drop files here with exactly these names, then run \`npm run build\` in \`shopify/\`. Every slot is optional; an empty slot
shows nothing (a dark band, a monogram or a toned frame) until its file arrives. The briefs, sizes and status are in \`docs/MEDIA_SLOTS.md\`.

| File | Use |
|---|---|
${mediaSlots(c).map(s => `| \`${s.file}\` | ${cell(s.use)} |`).join('\n')}

WebP for photographs (quality about 80). Films: silent, H.264 MP4 (WebM copy optional), 8 to 15 seconds, under 4 MB each.
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.mkdirSync(path.join(repo, 'docs'), {recursive: true});
  fs.writeFileSync(path.join(repo, 'docs/MEDIA_SLOTS.md'), mediaDoc());
  fs.writeFileSync(path.join(repo, 'images/README.md'), imagesReadme());
  const at = process.argv.indexOf('--audit');
  if (at > 0) fs.writeFileSync(process.argv[at + 1], `# ${loadCatalog().site}: media slots (${new Date().toISOString().slice(0, 10)})\n\nFolder: \`images/\` in the repo; run \`npm run build\` in \`shopify/\` after adding files.\n\n${table()}\n`);
  console.log('media docs written');
}
