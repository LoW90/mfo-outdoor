const lq = s => esc(s).replace(/'/g, '&#39;');
const sid = h => h.replace(/[^a-z0-9]+/g, '_');
const schema = obj => `{% schema %}\n${JSON.stringify(obj, null, 2)}\n{% endschema %}\n`;
const GEN = '{%- comment -%} Generated by shopify/planner/build.mjs from planner/data.json. Do not edit; rebuild. {%- endcomment -%}\n';
const MARK = 'mfe-planner-layer';
const css = `{{ 'mfe-planner.css' | asset_url | stylesheet_tag }}`;

