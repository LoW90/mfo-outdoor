/* ---------- files ---------- */
export function files(d = loadData(), c = loadCatalog()) {
  const out = [];
  const add = (p, text) => out.push({path: p, text});
  add('theme/sections/mfe-planner.liquid', plannerSection(d, c));
  add('theme/sections/mfe-connected.liquid', connectedSection(d, c));
  add('theme/sections/mfe-disclosure.liquid', disclosureSection(d, c));
  add('theme/snippets/mfe-planner-band.liquid', bandSnippet(d));
  add('theme/snippets/mfe-connected-band.liquid', connectedBand(d));
  add('theme/sections/mf-sister-stores.liquid', sistersSection(d));
  add('theme/snippets/mf-shortlist.liquid', shortlistSnippet(c));
  for (const p of PAGES.filter(p => p.section)) add(`theme/templates/${p.template}.json`, JSON.stringify({sections: {main: {type: p.section, settings: {}}}, order: ['main']}, null, 2) + '\n');
  add('theme/assets/mfe-plan-engine.js', fs.readFileSync(path.join(here, 'src/plan-engine.js'), 'utf8'));
  add('theme/assets/mfe-planner.js', fs.readFileSync(path.join(here, 'src/planner.js'), 'utf8'));
  add('theme/assets/mfe-planner.css', fs.readFileSync(path.join(here, 'src/planner.css'), 'utf8'));
  for (const [f, to] of [['mf-seo.liquid', 'snippets'], ['mf-business.liquid', 'sections'], ['mf-trust.liquid', 'sections'], ['mf-shortlist.js', 'assets'], ['mf-shortlist.css', 'assets'], ['en.default.json', 'locales']]) add(`theme/${to}/${f}`, fs.readFileSync(path.join(here, 'shared', f), 'utf8'));
  return out;
}

/* ---------- marked insertions into generated files (idempotent) ---------- */
export function patch(name, text) {
  const once = (from, to) => { if (!text.includes(from)) throw new Error(`${name}: "${from.slice(0, 60)}" not found`); text = text.replace(from, to); };
  if (text.includes(MARK)) return text;
  if (name === 'sections/mfe-home.liquid') {
    const at = text.indexOf('\n', text.indexOf('<div class="introline">'));
    if (at < 0) throw new Error('home section: trust strip not found');
    text = text.slice(0, at + 1) + `{%- comment -%} ${MARK} {%- endcomment -%}{% render 'mfe-planner-band' %}\n` + text.slice(at + 1);
    once('<section class="mf-room__band" id="guide"', `{% render 'mfe-connected-band' %}\n<section class="mf-room__band" id="guide"`);
    text = text.replace(/ target="_blank" rel="noopener">Visit /g, ' target="_blank" rel="sponsored noopener">Visit ');
    once('Tell us the space and we will reply within one business day.', 'Tell us the space and we will reply by email.');
    return text;
  }
  if (name === 'sections/mfe-header.liquid') {
    once('<a href="{{ routes.root_url }}#shop">Shop / Compare</a>', `<!-- ${MARK} --><a href="{{ routes.root_url }}pages/plan-your-outdoor-kitchen">Planner</a><a href="{{ routes.root_url }}#shop">The Edit</a><a href="{{ routes.root_url }}pages/connected-outdoors">Connected</a>`);
    text = text.replace('<a href="{{ routes.root_url }}#saved">Shortlist</a>', '');
    return text;
  }
  if (name === 'sections/mfe-footer.liquid') {
    once('<a href="{{ routes.root_url }}#approach">Disclosure</a>', `<!-- ${MARK} --><a href="{{ routes.root_url }}pages/how-we-are-paid">Affiliate disclosure</a>`);
    once(`<a href="{{ shop.privacy_policy.url | default: '/policies/privacy-policy' }}">Privacy</a>`, `<a href="{{ shop.privacy_policy.url | default: '/policies/privacy-policy' }}">Privacy</a><a href="{{ shop.terms_of_service.url | default: '/policies/terms-of-service' }}">Terms</a>`);
    once('<h4>Explore</h4>', '<h4>Explore</h4><a href="{{ routes.root_url }}pages/plan-your-outdoor-kitchen">Plan your outdoor kitchen</a>');
    return text;
  }
  if (name === 'layout/theme.liquid') {
    once(`{{ 'outdoor-estate.css' | asset_url | stylesheet_tag }}`, `{{ 'outdoor-estate.css' | asset_url | stylesheet_tag }}\n  {%- comment -%} ${MARK} {%- endcomment -%}${css}`);
    return text;
  }
  throw new Error('no patch for ' + name);
}
export const PATCHED = ['sections/mfe-home.liquid', 'sections/mfe-header.liquid', 'sections/mfe-footer.liquid', 'layout/theme.liquid'];

function main() {
  const check = process.argv.includes('--check');
  const differ = [];
  for (const f of files()) {
    const target = path.join(shop, f.path);
    const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (cur === f.text) continue;
    if (check) differ.push(f.path); else { fs.mkdirSync(path.dirname(target), {recursive: true}); fs.writeFileSync(target, f.text); }
  }
  for (const name of PATCHED) {
    const target = path.join(theme, name), cur = fs.readFileSync(target, 'utf8'), next = patch(name, cur);
    if (cur === next) continue;
    if (check) differ.push('theme/' + name); else fs.writeFileSync(target, next);
  }
  if (check) { if (differ.length) { console.error('Out of date:\n  ' + differ.join('\n  ')); process.exit(1); } console.log('Planner layer is current.'); return; }
  try {
    const zip = path.join(shop, 'dist', 'many-faces-outdoor-theme.zip');
    fs.rmSync(zip, {force: true});
    execFileSync('zip', ['-qrX', zip, '.', '-x', '.*'], {cwd: theme});
  } catch (e) { console.warn('zip skipped:', e.message); }
  console.log('Planner layer written.');
}
if (process.argv[1] === fileURLToPath(import.meta.url)) main();
