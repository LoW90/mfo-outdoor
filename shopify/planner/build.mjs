/**
 * The Outdoor Estate planner layer (hand-owned; not generated). Run AFTER shopify/build.mjs:
 *
 *   node build.mjs && node planner/build.mjs     build the theme, then add the planner pages on top
 *   node planner/build.mjs --check               exit 1 if the layer's files in theme/ are out of date
 *
 * Reads planner/data.json (made from site/index.html by tools/shopify-catalog.mjs) and writes NEW theme files: the
 * outdoor kitchen planner page, the connected-outdoors page, the "how we are paid" disclosure page, a planner band and a
 * connected band for the home page. It makes small marked insertions into generated files:
 *   sections/mfe-home.liquid     planner band after the trust strip, connected band before the field guide, maker
 *                                links marked sponsored, and the Ask band without a reply-time promise
 *   sections/mfe-header.liquid   Planner and Connected in the menu
 *   sections/mfe-footer.liquid   the disclosure page and terms in Information
 *   layout/theme.liquid          this store's palette stylesheet on every page
 * Because of those insertions, `node build.mjs --check` lists those files; that is expected (see README).
 * It also writes the shared Many Faces pieces the generator leaves to other scripts (mf-seo, mf-business, mf-trust,
 * mf-shortlist copied unchanged from mfo-home-gym; mf-sister-stores and the mf-shortlist config, placeholders until
 * LoW90/mfo-mLintelligence has this store), then rebuilds the theme zip.
 */
import fs from 'node:fs';
