import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';

const here = path.dirname(fileURLToPath(import.meta.url));
const shop = path.resolve(here, '..');
const theme = path.join(shop, 'theme');
const engine = createRequire(import.meta.url)('./src/plan-engine.js');
export const loadData = () => JSON.parse(fs.readFileSync(path.join(here, 'data.json'), 'utf8'));
export const loadCatalog = () => JSON.parse(fs.readFileSync(path.join(shop, 'catalog.json'), 'utf8'));

