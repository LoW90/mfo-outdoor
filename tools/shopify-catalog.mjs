// Writes the Shopify store's data from the static page, so site/index.html stays the single source of products,
// prices, programs and copy:
//   shopify/catalog.json        the input of the shared generator shopify/build.mjs (profile "sauna")
//   shopify/planner/data.json   what the hand-owned layer (shopify/planner/build.mjs) needs: build costs, programs,
//                               merchant status, the plan questions, connected-living copy and the disclosure
// Copy that exists only in the Shopify store (wordmark, notice line, the field guide, film notes) is in SHOPIFY below;
// shopify/planner/tests checks its figures against site/index.html.
//
//   node tools/shopify-catalog.mjs           write both files
//   node tools/shopify-catalog.mjs --check   exit 1 if either file differs from a fresh run
//
// The LoW90/mfo-mLintelligence registry entry for this store (portfolio/standalone.json) is pending; until it exists,
// this script is the source of shopify/catalog.json.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = new URL('..', import.meta.url);
const html = readFileSync(new URL('site/index.html', root), 'utf8');
const script = html.match(/<script>([\s\S]*?)<\/script>/)[1];

function pageData() {
  const context = { console, URL, Number, String, Object, JSON, Error, document: { readyState: 'loading', addEventListener() {} } };
  vm.createContext(context);
  vm.runInContext(script + '\n;globalThis.__api = { CHECKED, PRODUCTS, PROGRAMS, BUILD, BRANDS, FILMS, recommend, goLink, money };', context);
  return context.__api;
}
const decode = s => String(s).replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/\s+/g, ' ').trim();
function section(id) {
  const at = html.indexOf(`<section id="${id}"`);
  if (at < 0) throw new Error(`site/index.html: no section #${id}`);
  return html.slice(at, html.indexOf('</section>', at));
}
const one = (text, re, what) => { const m = text.match(re); if (!m) throw new Error('site/index.html: ' + what + ' not found'); return m[1]; };
const head = s => ({ eyebrow: decode(one(s, /<p class="eyebrow">([\s\S]*?)<\/p>/, 'eyebrow')), title: decode(one(s, /<h2>([\s\S]*?)<\/h2>/, 'h2')), intro: decode(one(s, /<p class="intro">([\s\S]*?)<\/p>/, 'intro')) });
const slug = name => String(name).toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const ISO = { '2 Nov 2026': '2026-11-02' };

