export const outputs = () => { const api = pageData(), d = data(api); return [['shopify/catalog.json', catalog(d, api)], ['shopify/planner/data.json', d]]; };

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check'); let stale = 0;
  for (const [file, value] of outputs()) {
    const text = JSON.stringify(value, null, 2) + '\n', url = new URL(file, root);
    if (existsSync(url) && readFileSync(url, 'utf8') === text) continue;
    if (check) { console.error(file + ' is out of date; run node tools/shopify-catalog.mjs'); stale++; } else { writeFileSync(url, text); console.log('wrote ' + file); }
  }
  if (check) { if (stale) process.exitCode = 1; else console.log('Shopify data is current.'); }
}
