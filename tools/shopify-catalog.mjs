export function data(api = pageData()) {
  const plan = section('plan'), connected = html.slice(html.indexOf('<section id="connected"'), html.indexOf('</section>', html.indexOf('<section id="connected"')));
  const disclosure = section('disclosure'), films = section('films');
  const costsNote = one(plan, /<details class="costs">[\s\S]*?<p class="note">([\s\S]*?)<\/p>/, 'costs note');
  return {
    $comment: 'Generated by tools/shopify-catalog.mjs from site/index.html. Do not edit here: change the page and regenerate.',
    checked: ISO[api.CHECKED] || (() => { throw new Error('unknown CHECKED date ' + api.CHECKED); })(),
    checkedLabel: api.CHECKED,
    title: decode(one(html, /<title>([\s\S]*?)<\/title>/, 'title')),
    description: one(html, /<meta name="description" content="([^"]+)">/, 'description'),
    hero: { eyebrow: decode(one(html, /<section class="hero"[\s\S]*?<p class="eyebrow">([\s\S]*?)<\/p>/, 'hero eyebrow')), title: decode(one(html, /<h1>([\s\S]*?)<\/h1>/, 'h1')), lead: decode(one(html, /<p class="lead">([\s\S]*?)<\/p>/, 'lead')), cta: decode(one(html, /<section class="hero"[\s\S]*?<a class="btn" href="#plan">([^<]+)<\/a>/, 'hero cta')) },
    plan: { ...head(plan), form: one(plan, /(<form class="panel" id="planForm" onsubmit="return false">[\s\S]*?<\/form>)/, 'plan form').replace(' onsubmit="return false"', ''), note: one(plan, /<\/div>\s*<p class="note">([\s\S]*?)<\/p>/, 'plan note').trim(), costsSummary: decode(one(plan, /<summary>([^<]+)<\/summary>/, 'costs summary')), costsNote: costsNote.trim() },
    build: api.BUILD,
    brands: { ...head(section('brands')) },
    edit: { ...head(section('edit')) },
    films: { ...head(films), list: api.FILMS.map(f => ({ id: f.id, title: f.title, line: f.line, aiGenerated: f.aiGenerated })) },
    connected: { eyebrow: decode(one(connected, /<p class="eyebrow">([\s\S]*?)<\/p>/, 'connected eyebrow')), title: decode(one(connected, /<h2>([\s\S]*?)<\/h2>/, 'connected h2')), intro: decode(one(connected, /<p class="intro">([\s\S]*?)<\/p>/, 'connected intro')),
      pillars: [...connected.matchAll(/<div class="pillar"><h3>([^<]+)<\/h3><p>([^<]+)<\/p><\/div>/g)].map(m => ({ title: decode(m[1]), text: decode(m[2]) })) },
    disclosure: { eyebrow: decode(one(disclosure, /<p class="eyebrow">([\s\S]*?)<\/p>/, 'eyebrow')), title: decode(one(disclosure, /<h2>([\s\S]*?)<\/h2>/, 'h2')), text: decode(one(disclosure, /<p class="intro">([\s\S]*?)<\/p>/, 'disclosure')) },
    programs: api.PROGRAMS,
    // Merchant status, as on the page: a program exists for every merchant but none has approved us ("Not applied yet"),
    // so every link is untracked and carries only our utm tags. "tracked" once a program approves (then swap the link).
    merchants: [...new Set(api.PRODUCTS.map(p => p.where))].map(where => ({ name: where, status: 'pending', programs: [...new Set(api.PRODUCTS.filter(p => p.where === where).map(p => p.program))] })),
    products: api.PRODUCTS.map(p => ({ id: p.id, handle: p.id.startsWith(slug(p.brand).split('-')[0]) ? p.id : `${slug(p.brand).split('-')[0]}-${p.id}`, brand: p.brand, name: p.name, cat: p.cat, connected: !!p.connected, price: p.price, wasPrice: p.wasPrice || null, priceNote: p.priceNote || null, stock: p.stock || null, where: p.where, url: p.url, link: api.goLink(p), program: p.program })),
    sisters: one(html, /Sister stores for mfo-outdoor: ([a-z, -]+)\./, 'sister stores').split(', '),
  };
}

